export class PlatformContentService {
    static getCurrentPlatform(): AppPlatform {
        return getAppPlatform();
    }

    static getDetails(platform: AppPlatform = getAppPlatform()): PlatformDetails {
        return PLATFORM_DATA[platform] || PLATFORM_DATA.web;
    }

    static getPlatformName(platform: AppPlatform = getAppPlatform()): string {
        switch (platform) {
            case 'windows': return 'ویندوز دسکتاپ';
            case 'android': return 'موبایل اندروید';
            case 'pwa': return 'وب پیش‌رونده (PWA)';
            case 'web':
            default: return 'هاست و وب‌سرویس ابری';
        }
    }

    static getSmsHelpText(platform: AppPlatform = getAppPlatform()): string {
        if (platform === 'android') {
            return 'در نسخه اندروید، با لمس دکمه «ارسال با سیم‌کارت گوشی»، پیامک فاکتور مستقیماً و بدون نیاز به خرید شارژ پنل یا اینترنت از طریق سیم‌کارت گوشی شما با متن و لینک فاکتور آماده ارسال می‌شود.';
        }
        if (platform === 'windows') {
            return 'در نسخه ویندوز، پیامک‌ها از طریق وب‌سرویس پیامک هاست یا پل ارتباطی با اپلیکیشن اندروید ارسال می‌شوند.';
        }
        return 'در نسخه وب، پیامک‌ها از طریق درگاه وب‌سرویس پیامکی تعریف شده در تنظیمات یا لینک پرداخت اینترنتی ارسال می‌گردند.';
    }

    static getPerformanceNotice(platform: AppPlatform = getAppPlatform()): string {
        if (platform === 'windows') {
            return '🚀 بهینه‌سازی سرعت ویندوز: پردازش‌ها به صورت کاملاً غیرمسدودکننده (Non-blocking) در رشته‌های محلی اجرا می‌شوند تا عملکرد سیستم با نهایت سرعت حفظ شود.';
        }
        if (platform === 'android') {
            return '⚡ بهینه‌سازی مصرف باتری و اینترنت موبایل: همگام‌سازی در حجم داده کم و فقط برای رکوردهای تغییر یافته انجام می‌شود.';
        }
        return '☁️ همگام‌سازی ابری: اطلاعات به صورت چندکاربره و بلادرنگ با سرور مرکزی در تبادل است.';
    }
}
